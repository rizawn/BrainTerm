#!/usr/bin/env python3
"""Generates bt_build_stamp.h with short git hash (+ '-dirty' if uncommitted changes)
and local build timestamp ('YYYY-MM-DD HH:MM'). Only rewrites output when changed."""
import datetime
import pathlib
import subprocess
import sys


def git_out(repo: str, *args: str) -> str:
    try:
        r = subprocess.run(
            ["git", "-C", repo, *args],
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        return r.stdout.strip() if r.returncode == 0 else ""
    except Exception:
        return ""


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_build_stamp.py <source_root> <output_header>\n")
        return 2

    repo = sys.argv[1]
    out_path = pathlib.Path(sys.argv[2])

    short_hash = git_out(repo, "rev-parse", "--short", "HEAD") or "nogit"
    dirty = bool(git_out(repo, "status", "--porcelain"))
    if short_hash != "nogit" and dirty:
        short_hash += "-dirty"

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    stamp = f"{short_hash} · {now_str}"

    content = (
        "/* Auto-generated by scripts/gen_build_stamp.py — do not edit. */\n"
        "#ifndef BT_BUILD_STAMP_H\n"
        "#define BT_BUILD_STAMP_H\n"
        f'#define BT_BUILD_HASH  "{short_hash}"\n'
        f'#define BT_BUILD_TIME  "{now_str}"\n'
        f'#define BT_BUILD_STAMP "{stamp}"\n'
        "#endif\n"
    )

    if out_path.exists():
        try:
            if out_path.read_text(encoding="utf-8") == content:
                return 0
        except OSError:
            pass

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
