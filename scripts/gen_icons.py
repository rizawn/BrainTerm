def to_path(geom):
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    d = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)
            d.append("M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts[:-1]) + "Z")
    return " ".join(d)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, parts in ICONS.items():
        geom = unary_union(parts).simplify(0.02)
        svg = ('<?xml version="1.0" encoding="UTF-8"?>\n'
               '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24">'
               f'<path fill="#bebebe" fill-rule="evenodd" d="{to_path(geom)}"/></svg>\n')
        (OUT / f"{name}-symbolic.svg").write_text(svg, encoding="utf-8")
    xml = ["    <!-- generated by scripts/gen_icons.py -->"]
    for name in ICONS:
        xml.append(f'    <file alias="icons/scalable/actions/{name}-symbolic.svg">'
                   f"icons/{name}-symbolic.svg</file>")
    (OUT / "gresource-fragment.txt").write_text("\n".join(xml) + "\n", encoding="utf-8")
    print(f"wrote {len(ICONS)} icons to {OUT}")


if __name__ == "__main__":
    main()
